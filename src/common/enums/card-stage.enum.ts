/**
 * Гишүүний Wallet картын явц — ЯЛГААТАЙ арга хэмжээ шаардах дөрвөн байдал.
 *
 * Урьд нь зөвхөн «карт байна / байхгүй» гэсэн хоёр утга байсан бөгөөд энэ нь
 * тэс өөр гурван нөхцөлийг нэг дор нийлүүлдэг байв:
 *
 *   • Loopy руу дугаар нь огт хүрээгүй → гишүүн карт үүсгэх БОЛОМЖГҮЙ.
 *     Энэ бол системийн алдаа — ажилтан засах ёстой.
 *   • Дугаар нь хүрсэн ч гишүүн үүсгээгүй → гишүүнд линк илгээх ёстой.
 *   • Карт үүссэн ч Wallet-д нэмээгүй → push мэдэгдэл ХҮРЭХГҮЙ.
 *     Эрх дуусах сануулга очихгүй тул залгах ёстой.
 */
export enum CardStage {
  /** Loopy-гийн зөвшөөрөгдсөн жагсаалтад алга — ★ засвар шаардлагатай. */
  NOT_ALLOWED = 'not_allowed',
  /** Зөвшөөрөгдсөн, гэхдээ карт үүсгээгүй. */
  NO_CARD = 'no_card',
  /** Карт үүссэн, гэхдээ Wallet-д нэмээгүй — мэдэгдэл хүрэхгүй. */
  NO_WALLET = 'no_wallet',
  /** Бүрэн — карт Wallet дээр байгаа, мэдэгдэл хүрнэ. */
  ACTIVE = 'active',
}

export const CARD_STAGE_LABEL: Record<CardStage, string> = {
  [CardStage.NOT_ALLOWED]: 'Loopy-д бүртгэгдээгүй',
  [CardStage.NO_CARD]: 'Карт үүсгээгүй',
  [CardStage.NO_WALLET]: 'Wallet-д нэмээгүй',
  [CardStage.ACTIVE]: 'Идэвхтэй',
};
